export function variant(definition: LabDefinition, seed: number): LabDefinition {
  const subnet = calculateSubnet(definition.client, definition.prefix)
  const candidates = Array.from(
    { length: 254 },
    (_, i) => `${definition.client.split('.').slice(0, 3).join('.')}.${i + 1}`,
  ).filter(
    (address) =>
      ![
        subnet.network,
        subnet.broadcast,
        definition.client,
        definition.gateway,
        definition.dns,
        definition.server,
        '192.0.2.54',
        '192.0.2.254',
      ].includes(address) && contains(address, definition.gateway, definition.prefix),
  )
  const client =
    candidates[(Math.abs(Math.trunc(seed)) - 1) % candidates.length] ?? definition.client
  const copy = structuredClone(definition)
  copy.client = client
  copy.hints = copy.hints.map((h) => h.replaceAll(definition.client, client))
  copy.brief = copy.brief.replaceAll(definition.client, client)
  return copy
}
export function definitionState(id: string, seed = 0) {
  const definition = extendedLabs.find((l) => l.id === id)
  return definition ? createNetwork(seed ? variant(definition, seed) : definition) : undefined
}
