export function packageChecks(id: string): PackageCheck[] {
  const p = learningPackages.find((p) => p.id === id)!
  const explanation = explanations[id]!
  const checks: PackageCheck[] = [
    {
      id: 'choice',
      skill: id === 'web' ? 'services' : p.skill,
      form: 'choice',
      prompt: p.question,
      options: p.options,
      answer: p.correct,
      explanation: explanation[0],
    },
    {
      id: 'calculation',
      skill: p.skill,
      form: 'calculation',
      prompt: p.calculation,
      answer: p.answer,
      explanation: explanation[1],
    },
    {
      id: 'contradiction',
      skill:
        id === 'network'
          ? 'transport'
          : id === 'linux' || id === 'operations'
            ? 'services'
            : p.skill,
      form: 'contradiction',
      prompt: p.contradiction,
      options: p.choices,
      answer: p.contradictionCorrect,
      explanation: explanation[2],
    },
    ...(extra[id] ?? []),
  ]
  return [
    ...checks,
    ...[...new Set(checks.map((c) => c.skill))].map((skill) => {
      const [prompt, options, answer, explanation] = reviewCases[skill]
      return {
        id: `review-${skill}`,
        skill,
        form: 'contradiction' as const,
        prompt,
        options,
        answer,
        explanation,
      }
    }),
  ]
}
