export function remediationLesson(id: LearningErrorId) {
  return remediationLessons.find((lesson) => lesson.id === id)!
}
export function remediationChecks(a: Pick<RemediationAttempt, 'errorId' | 'phase' | 'variant'>) {
  const variants = remediationLesson(a.errorId)[a.phase]
  return a.variant === 0 ? variants[0] : variants[1]
}
export function remediationPassed(a: RemediationAttempt) {
  return (
    !!a.completedAt &&
    a.answers.every((answer, i) => answer.choice === remediationChecks(a)[i]!.correct)
  )
}
