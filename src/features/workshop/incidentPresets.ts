export function graphDebrief(
  graph: IncidentGraph,
  steps: Array<{ node: string; choice: number }>,
  score: number,
) {
  return [
    `# ${graph.title}`,
    `Учебная попытка: ${score}/100. Не является независимой аттестацией.`,
    ...steps.map((s, i) => {
      const node = graph.nodes.find((n) => n.id === s.node)!,
        choice = node.choices[s.choice]!
      return `${i + 1}. ${node.prompt}\n   Действие: ${choice.label}\n   ${choice.useful ? 'Обосновано' : 'Требует пересмотра'}: ${choice.explanation}`
    }),
  ].join('\n\n')
}
