import { sampleGraph, type IncidentGraph } from './graph'
type Stage = [string, string, string, string, string]
function make(id: string, title: string, stages: Stage[]): IncidentGraph {
  return {
    schemaVersion: 1,
    id: `GRAPH-00000000-0000-4000-8000-${id.padStart(12, '0')}`,
    title,
    start: 'stage-0',
    nodes: stages.map(([prompt, action, wrong, explanation, correction], i) => {
      const useful = {
        label: action,
        to: i === stages.length - 1 ? 'END' : `stage-${i + 1}`,
        useful: true,
        explanation,
      }
      const other = { label: wrong, to: `stage-${i}`, useful: false, explanation: correction }
      return { id: `stage-${i}`, prompt, choices: i % 2 ? [other, useful] : [useful, other] }
    }),
  }
}
