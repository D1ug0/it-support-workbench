import type { QuizQuestion } from '../learning/questions'

export interface LabQuestion extends QuizQuestion {
  hint: string
}
export interface AcademyCourse {
  id: string
  title: string
  summary: string
  minutes: number
  prerequisites: string[]
  goals: string[]
  concepts: Array<{ title: string; body: string }>
  commands: Array<{ command: string; shell: 'CMD' | 'PowerShell'; purpose: string }>
  checklist: string[]
  pitfall: string
  lab: { briefing: string; evidence: string; questions: LabQuestion[] }
  sources: Array<{ title: string; url: string }>
  reviewedAt: string
}
type Assessment = [string, string[], number, string, string, number?]
type Definition = Omit<AcademyCourse, 'lab' | 'reviewedAt'> & {
  lab: { briefing: string; evidence: string; questions: Assessment[] }
}
const learn = 'https://learn.microsoft.com/en-us/'
const source = (title: string, path: string) => ({
  title: `Microsoft Learn · ${title}`,
  url: learn + path,
})
function course(value: Definition): AcademyCourse {
  return {
    ...value,
    reviewedAt: '2026-10-10',
    lab: {
      ...value.lab,
      questions: value.lab.questions.map(
        ([prompt, choices, correct, explanation, hint, sourceIndex], index) => ({
          id: `ADV-${value.id.toUpperCase()}-${index + 1}`,
          category: value.title,
          prompt,
          choices,
          correct,
          explanation,
          hint,
          source: value.sources[sourceIndex ?? 0]!,
        }),
      ),
    },
  }
}

