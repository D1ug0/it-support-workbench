export function userGuideMarkdown() {
  return [
    '# Как пользоваться IT Support Workbench',
    guideIntroduction,
    '## Первый запуск',
    ...firstSteps.map((step, index) => `${index + 1}. **${step.title}** — ${step.description}`),
    '## Первые пять занятий',
    ...starterLessons.map((lesson, index) => `${index + 1}. **${lesson.title}** — ${lesson.goal}`),
    '## Как проходит занятие',
    ...sessionSteps.map((step, index) => `${index + 1}. **${step.title}** — ${step.description}`),
    '## Как читать прогресс',
    ...progressMeanings.map((item) => `### ${item.title}\n\n${item.description}`),
    '## Когда какой раздел открыть',
    ...guideTools.map((tool) => `- **${tool.title}** — ${tool.when}`),
    '## Частые вопросы',
    ...guideFaq.map((item) => `### ${item.question}\n\n${item.answer}`),
    'Откройте «Как пользоваться» в меню веб-приложения, чтобы прочитать текущую редакцию и перейти к заданиям. Этот файл содержит общую инструкцию, без личных результатов и заметок.',
  ].join('\n\n')
}
