// Use the same order and titles as the learner journey.
export const starterLessons = foundationSkills.flatMap((skill) => {
  const course = workshopCourses.find((value) => value.skill === skill)
  return course
    ? [
        {
          id: course.id,
          title: course.title,
          goal: starterGoals[skill] ?? course.why,
          to: `/learning?lesson=${course.id}`,
        },
      ]
    : []
})

